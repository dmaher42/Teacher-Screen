const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM } = require('jsdom');
const root = path.resolve(__dirname, '..');
const picture = 'data:image/png;base64,iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==';

async function run() {
    const response = await fetch('https://cdn.jsdelivr.net/npm/quill@2.0.3/dist/quill.min.js');
    assert(response.ok);
    const quillSource = await response.text();
    const dom = new JSDOM('<!doctype html><body></body>', { runScripts: 'outside-only', url: 'http://localhost/' });
    const w = dom.window;
    const scheduled = [];
    w.setTimeout = fn => { scheduled.push(fn); return scheduled.length; };
    w.requestAnimationFrame = () => 0;
    w.cancelAnimationFrame = () => {};
    w.Range.prototype.getBoundingClientRect = () => ({ top: 0, bottom: 0, left: 0, right: 0, width: 0, height: 0 });
    w.Range.prototype.getClientRects = () => [];
    let changes = 0;
    w.TeacherScreenWidgetState = { notifyChanged: () => changes++ };
    w.eval(quillSource);
    w.eval(fs.readFileSync(path.join(root, 'js/utils/text-board-images.js'), 'utf8'));
    w.eval(fs.readFileSync(path.join(root, 'js/widgets/rich-text-widget.js'), 'utf8') + '\nwindow.RichTextWidget = RichTextWidget;');
    const makeWidget = data => {
        const widget = new w.RichTextWidget();
        w.document.body.append(widget.element);
        if (data) widget.deserialize(data);
        scheduled[widget.initTimer - 1]();
        widget.quill.update('silent');
        widget.quill.history.clear();
        Object.defineProperty(widget.quill.root, 'clientWidth', { configurable: true, value: 1000 });
        widget.editorContainer.getBoundingClientRect = () => ({ left: 0, top: 0, width: 1100, height: 800 });
        return widget;
    };
    const geometry = image => {
        Object.defineProperty(image, 'naturalWidth', { configurable: true, value: 200 });
        Object.defineProperty(image, 'naturalHeight', { configurable: true, value: 100 });
        image.getBoundingClientRect = () => {
            const width = image.getAttribute('width') || '200';
            const pixels = width.endsWith('%') ? parseFloat(width) * 10 : parseFloat(width);
            return { left: 20, top: 80, width: pixels, height: pixels / 2 };
        };
        return image;
    };
    const widget = makeWidget({ content: `<p>Before</p><p><img src="${picture}" width="80" height="40" alt="diagram"></p><p>After</p>` });
    let image = geometry(widget.quill.root.querySelector('img'));
    const controls = widget.imageControls;
    assert(controls);
    assert.equal(image.getAttribute('width'), '80', 'Existing image dimensions stay untouched before selection/resizing');
    controls.select(image);
    assert(!controls.host.hidden);
    controls.commit(60);
    assert.equal(image.getAttribute('width'), '60%');
    assert.equal(image.getAttribute('height'), null, 'Intrinsic aspect ratio replaces a fixed height only after explicit resizing');
    assert.equal(image.getAttribute('alt'), 'diagram');
    assert.equal(widget.quill.getText(), 'Before\n\nAfter\n');
    assert(changes > 0, 'Resizing uses the normal save/sync notification');
    widget.quill.history.undo();
    assert.equal(image.getAttribute('width'), '80');
    assert.equal(image.getAttribute('height'), '40');
    widget.quill.history.redo();
    assert.equal(image.getAttribute('width'), '60%');
    const saved = JSON.parse(JSON.stringify(widget.serialize()));
    assert(!saved.content.includes('text-board-image-overlay'));
    const reloaded = makeWidget(saved);
    assert.equal(reloaded.quill.root.querySelector('img').getAttribute('width'), '60%');
    console.log('PASS: Real Quill image formats, aspect ratio, one-step undo/redo, autosave notification and JSON reload retain content.');

    controls.input.value = '36';
    controls.input.dispatchEvent(new w.Event('change', { bubbles: true }));
    assert.equal(image.getAttribute('width'), '36%');
    const handle = controls.frame.querySelector('[data-image-corner="se"]');
    handle.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
    assert.equal(image.getAttribute('width'), '37%');
    const event = (x, y) => ({ target: handle, pointerId: 1, button: 0, clientX: x, clientY: y, preventDefault() {}, stopPropagation() {} });
    controls.beginDrag(event(0, 0)); controls.moveDrag(event(130, 10));
    assert.equal(image.getAttribute('width'), '37%', 'A drag preview must not change or autosave content');
    assert.equal(parseFloat(controls.frame.style.width) / parseFloat(controls.frame.style.height), 2);
    controls.endDrag(event(130, 10), true);
    assert.equal(image.getAttribute('width'), '50%');
    widget.quill.history.undo(); assert.equal(image.getAttribute('width'), '37%', 'A complete drag is one undo step');
    controls.beginDrag(event(0, 0)); controls.moveDrag(event(100, 10)); controls.endDrag(event(100, 10), false);
    assert.equal(image.getAttribute('width'), '37%', 'Cancel leaves content unchanged');
    controls.commit(300); assert.equal(image.getAttribute('width'), '100%');
    controls.tools.querySelector('[data-image-size="original"]').click(); assert.equal(image.getAttribute('width'), '20%');
    controls.tools.querySelector('[data-image-size="fit"]').click(); assert.equal(image.getAttribute('width'), '100%');
    widget.quill.setSelection(widget.quill.getIndex(w.Quill.find(image)), 1, 'silent');
    controls.input.dispatchEvent(new w.KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
    assert(controls.host.hidden, 'Escape must not reopen the selection while returning focus to Quill');
    console.log('PASS: Numeric/keyboard sizing, aspect-locked drag preview/commit/cancel and width bounds.');

    widget.quill.clipboard.dangerouslyPasteHTML(widget.quill.getLength() - 1, `<p><img src="${picture}" width="70%" alt="pasted"></p>`, 'user');
    widget.quill.update('silent');
    image = geometry(widget.quill.root.querySelector('img[alt="pasted"]'));
    controls.select(image); controls.commit(25);
    assert.equal(image.getAttribute('width'), '25%');
    widget.teacherOnly = true;
    assert.equal(widget.serializeForProjector().content, '');
    widget.teacherOnly = false;
    assert(widget.serializeForProjector().content.includes('width="25%"'));
    w.APP_MODE = 'projector';
    const projector = makeWidget(widget.serializeForProjector());
    assert.equal(projector.imageControls, null);
    assert.equal(projector.element.querySelector('.text-board-image-overlay'), null);
    assert.equal(projector.quill.root.querySelector('img[alt="pasted"]').getAttribute('width'), '25%');
    w.APP_MODE = 'teacher';
    widget.isDisplayMode = true; widget.updateDisplayModeUI(); assert(controls.host.hidden);
    widget.isDisplayMode = false; widget.updateDisplayModeUI(); controls.select(image);
    image.remove(); controls.refresh(); assert(controls.host.hidden);
    widget.remove({ notify: false }); assert.equal(widget.imageControls, null);
    console.log('PASS: Pasted image round trip, teacher-only redaction, projector rendering without controls, display mode and deletion lifecycle.');
}
run().catch(error => { console.error(error); process.exitCode = 1; });
